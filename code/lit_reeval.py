def parse(s):
    return [int(x) for x in s.split()]


def main():
    import os
    if os.path.exists("lit_sboxes_raw.json"):
        raw = json.load(open("lit_sboxes_raw.json"))
        boxes = {"Lambić 2014 (CSF) – kaotik harita + bileşim": raw["1-s2.0-S0960077913001975-main#1"],
                 "Zheng, Bao 2022 (Entropy) – kaskad kaotik harita [PDF]": raw["entropy-24-01827#1"],
                 "Ali, Khan vd. 2022 (PeerJ CS) – PWLCM [PDF]": raw["peerj-cs-08-940#1"],
                 "Razaq, Ramzan vd. 2026 (Sci. Rep.) – Schreier grafları [PDF, Tablo 4]": raw["41598_2026_Article_56441#2"]}
        if os.path.exists("lit_pone_variants.json"):
            boxes["Banga, Mahmood vd. 2025 (PLOS One) – sekizgen geometri + kaos [PDF, tek hücre düzeltmeli]"] = \
                json.load(open("lit_pone_variants.json"))["204"]
    else:  # release version: the PDF-extracted tables are in lit_sboxes_valid.json
        valid = json.load(open("lit_sboxes_valid.json"))
        boxes = {k: v for k, v in valid.items() if not k.startswith("Bu çalışma") and k != "AES"}
    rejected = []
    for name, s in RAW.items():
        if "[PDF]" in name or name.split(" (")[0] in ("Zheng, Bao 2022", "Ali, Khan vd. 2022", "Razaq, Ramzan vd. 2026"):
            continue  # the PDF-extracted versions are used
        if any(name.split(" (")[0] in k for k in boxes):
            continue  # already loaded (release version)
        v = parse(s)
        if len(v) == 256 and sorted(v) == list(range(256)):
            boxes[name] = v
        else:
            rejected.append((name, len(v), len(set(v))))
    boxes["Bu çalışma – Aday A (2D-LCChM)"] = np.load("lccm_multikey_best.npy").tolist()
    boxes["Bu çalışma – Aday B (2D-LCChM)"] = np.load("lccm_coord_best.npy").tolist()
    boxes["AES"] = L.aes_sbox().tolist()
    lines = ["Literatur S-box'larinin ayni kodla yeniden degerlendirilmesi (Artuger/Ozkaynak kapsam disi)",
             "Reddedilen (256 farkli deger testi basarisiz; HTML'den cikarim hatasi): " +
             ("; ".join(f"{n} [{k} deger, {u} farkli]" for n, k, u in rejected) if rejected else "yok"), "",
             f"{'S-box':<62} {'koordNL min/ort/maks':>21} {'cNL':>4} {'LP':>7} {'DU':>3} {'SAC':>7} {'BICNL':>7} {'BICSAC':>7} {'FP':>3}  makalede raporlanan"]
    rows = []
    for name, v in boxes.items():
        a = L.analyze(np.array(v, dtype=np.int64))
        rows.append((name, a))
        lines.append(f"{name:<62} {a['NL_min']:>5}/{a['NL_avg']:>6.2f}/{a['NL_max']:>3} {a['comp_NL']:>4} {a['LP']:>7.4f} {a['DU']:>3} "
                     f"{a['SAC_avg']:>7.4f} {a['BIC_NL_avg']:>7.2f} {a['BIC_SAC_avg']:>7.4f} {a['fixed_points']:>3}  {REPORTED.get(name, '')}")
    lines.append("\nGozlem: koordinat NL ort ile bilesen NL arasindaki fark (koord ort - cNL):")
    for name, a in rows:
        lines.append(f"  {name:<62} {a['NL_avg'] - a['comp_NL']:+6.2f}")
    print("\n".join(lines)); open("lit_reeval_results.txt", "w", encoding="utf-8").write("\n".join(lines))
    json.dump({k: v for k, v in boxes.items()}, open("lit_sboxes_valid.json", "w"), indent=0)


if __name__ == "__main__":
    main()
